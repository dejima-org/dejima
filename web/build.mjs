// Builds web/index.html: one self-contained file, because that is the only
// shape ttyd can serve. Its HTTP handler answers exactly three paths - the
// token endpoint, a redirect, and the index - so there is no route a separate
// .js or .css could be fetched from, and --index replaces the whole frontend
// with a single file. Inlining is not an optimisation here, it is the
// interface.
//
// Nothing is fetched at runtime either: the sandbox restricts outbound
// traffic to an allowlist, so a CDN reference would simply fail to load.
//
// Usage: npm ci && node build.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

// Order matters: each file attaches to the shared DEJIMA object, and config.js
// parses the tmux prefix through keys.js, mouse.js through sgr.js and modes.js,
// and main.js through all of them.
const CLIENT_SOURCES = [
  'src/sgr.js',
  'src/modes.js',
  'src/keys.js',
  'src/osc52.js',
  'src/config.js',
  'src/protocol.js',
  'src/mouse.js',
  'src/gestures.js',
  'src/viewport.js',
  'src/keyboard.js',
  'src/toolbar.js',
  'src/main.js'
];

// Everything the output depends on, for the staleness check in test/remote.bats
// - index.html is committed, so nothing forces a rebuild except noticing that
// the sources moved on without it. The check compares this manifest against
// the tree AND the page's own Sources stamp against this manifest; both are
// needed, since the first alone passes on a commit that rebuilds the manifest
// and leaves the page behind.
const MANIFEST_SOURCES = [
  'package-lock.json',
  'src/config.js',
  'src/gestures.js',
  'src/keyboard.js',
  'src/keys.js',
  'src/main.js',
  'src/modes.js',
  'src/mouse.js',
  'src/osc52.js',
  'src/page.css',
  'src/protocol.js',
  'src/sgr.js',
  'src/template.html',
  'src/toolbar.js',
  'src/viewport.js'
];

const read = (relative) => readFileSync(join(here, relative), 'utf8');
const sha256 = (text) => createHash('sha256').update(text).digest('hex');

// A literal </script> inside an inlined script would end the element early.
// Any occurrence is inside a string or a regex - anywhere else it would not be
// valid JavaScript - where the backslash is a no-op.
const escapeForScript = (js) => js.replace(/<\/script/gi, '<\\/script');

// A function replacer, so a $& or $1 in the payload is not treated as a
// substitution pattern.
function fill(html, placeholder, content) {
  const marker = `/*${placeholder}*/`;
  if (!html.includes(marker)) throw new Error(`template has no ${marker} placeholder`);
  return html.replace(marker, () => content);
}

const client = CLIENT_SOURCES.map((file) => read(file)).join('\n');

let html = read('src/template.html');
html = fill(html, 'XTERM_CSS', read('node_modules/@xterm/xterm/css/xterm.css'));
html = fill(html, 'PAGE_CSS', read('src/page.css'));
html = fill(html, 'XTERM_JS', escapeForScript(read('node_modules/@xterm/xterm/lib/xterm.js')));
html = fill(html, 'ADDON_FIT_JS', escapeForScript(read('node_modules/@xterm/addon-fit/lib/addon-fit.js')));
html = fill(html, 'CLIENT_JS', escapeForScript(client));

const manifest = MANIFEST_SOURCES.map((file) => `${sha256(read(file))}  ${file}\n`).join('');
html = html.replace(
  '<!--BUILD_STAMP-->',
  () =>
    `<!-- Generated by web/build.mjs - do not edit. Sources: ${sha256(manifest)} -->`
);

writeFileSync(join(here, 'index.html'), html);
writeFileSync(join(here, 'sources.sha256'), manifest);

console.log(`web/index.html: ${html.length} bytes`);
console.log(`web/sources.sha256: ${MANIFEST_SOURCES.length} files`);
